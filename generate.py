#!/usr/bin/env python3
"""Генерирует Caddyfile и конфиг Homepage из services.yaml.

Поля сервиса:
  name, title, group, backend, scheme (http|https), path, insecure,
  auth (вход через Caddy basic_auth), icon, description, href (переопределяет ссылку).

Домен берётся из переменной ZONE (по умолчанию lab.example).
Логин и хеш пароля для basic_auth берутся из переменных окружения Caddy:
  PANEL_USER, PANEL_PASS_HASH (получить: caddy hash-password).
"""
import os
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).parent
ZONE = os.environ.get('ZONE', 'lab.example')
OUT = ROOT / 'generated'


def caddy_block(s: dict) -> str:
    name, backend = s['name'], s['backend']
    scheme = s.get('scheme', 'http')
    path = (s.get('path') or '').rstrip('/')
    lines = [f'{name}.{ZONE} {{', '    tls internal']
    if s.get('auth'):
        lines += ['    basic_auth {',
                  '        {env.PANEL_USER} {env.PANEL_PASS_HASH}',
                  '    }']
    if path:
        lines.append(f'    redir / {path}/')
    proxy = f'    reverse_proxy {scheme}://{backend}'
    if scheme == 'https':
        proxy += ' {\n        transport http {\n            tls\n'
        if s.get('insecure'):
            proxy += '            tls_insecure_skip_verify\n'
        proxy += '        }\n    }'
    lines.append(proxy)
    lines.append('}')
    return '\n'.join(lines)


def homepage_block(services: list[dict]) -> list[dict]:
    groups: dict[str, list[dict]] = {}
    for s in services:
        groups.setdefault(s.get('group', 'Other'), []).append(s)
    result = []
    for group, items in sorted(groups.items()):
        entries = []
        for s in items:
            body = {
                'href': s.get('href') or f"https://{s['name']}.{ZONE}/",
                'description': s.get('description', ''),
            }
            icon = s.get('icon')
            if icon and not icon.startswith('local:'):
                body['icon'] = f"{icon}.png"
            entries.append({s.get('title', s['name']): body})
        result.append({group: entries})
    return result


def main() -> int:
    cfg = yaml.safe_load((ROOT / 'services.yaml').read_text(encoding='utf-8')) or {}
    services = cfg.get('services', [])

    names = [s['name'] for s in services]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        print(f'ошибка: повторяются имена: {", ".join(dupes)}', file=sys.stderr)
        return 1

    OUT.mkdir(exist_ok=True)
    caddyfile = ('# AUTOGENERATED by generate.py, do not edit by hand\n\n'
                 + '\n\n'.join(caddy_block(s) for s in services) + '\n')
    (OUT / 'Caddyfile.apps').write_text(caddyfile, encoding='utf-8')
    print(f'✓ generated/Caddyfile.apps ({len(services)} сервисов)')

    (OUT / 'homepage-services.yaml').write_text(
        yaml.safe_dump(homepage_block(services), allow_unicode=True,
                       sort_keys=False, default_flow_style=False),
        encoding='utf-8')
    print('✓ generated/homepage-services.yaml')
    return 0


if __name__ == '__main__':
    sys.exit(main())
